async function seed() {
  try {
    await mongoose.connect(process.env.MONGODB_URI);
    console.log('Connected to MongoDB');

    let reqCount = 0;
    for (const r of REQUESTS) {
      await BloodRequest.findOneAndUpdate(
        { patientName: r.patientName, hospital: r.hospital },
        { $set: r },
        { upsert: true, new: true }
      );
      reqCount++;
    }
    console.log(`Blood Requests seeded: ${reqCount}`);

    let donorCount = 0;
    for (const d of DONORS) {
      await Donor.findOneAndUpdate(
        { uid: d.uid },
        { $set: d },
        { upsert: true, new: true }
      );
      donorCount++;
    }
    console.log(`Donors seeded: ${donorCount}`);

    const totalReqs = await BloodRequest.countDocuments();
    const totalDonors = await Donor.countDocuments();
    console.log(`Total in DB -> Requests: ${totalReqs}, Donors: ${totalDonors}`);
  } catch (err) {
    console.error('Error seeding requests/donors:', err);
  } finally {
    process.exit(0);
  }
}

seed();
